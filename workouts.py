def plans_for(days):
    if days not in PLANS:
        raise ValueError("اختر من 2 إلى 6 أيام")
    out = []
    for i, (name, desc, level, sched) in enumerate(PLANS[days]):
        week = []
        for d, label in enumerate(DAYS):
            if d in sched:
                title, ex = W[sched[d]]
                week.append({"day": label, "title": title, "exercises": [
                    {"name": n, "sets": s, "video_url": f"https://www.youtube.com/watch?v={EXERCISE_VIDEOS[n]}"}
                    for n, s in ex
                ]})
            else:
                week.append({"day": label, "title": None, "exercises": []})
        out.append({"id": f"{days}-{i}", "name": name, "desc": desc, "level": level, "week": week})
    return out
